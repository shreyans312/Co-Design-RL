h1("6. Why RL4CO PPO struggled in co-design")
p("The run stopped at 78 of 500 iterations, so this is unstable and unconverged, not proven to fail. Likely causes, strongest first:")
bullet("the RL4CO script reused the design-distribution setup of the first SB3 attempt (entropy weight 5.0 at the start). Iteration 1 sampled designs with a mean of 3939 kWp PV and 118 kWh battery, giving a mean reward of -13,505 (std 66,000). 25 of 78 iterations had a mean reward below -1000, with a median of -635, against about -103 for the manual DDPG. The stabilised SB3 run avoided this with entropy weight 0.01, a narrow initial design range (log-mean 0 to 1, log-std 1), a 10% design warm-up and rewards scaled by 0.01. None of these were applied to RL4CO.", "Design distribution blew up: ")
bullet("RL4CO's PPO is built for combinatorial problems where one solution gets one reward. Here the whole 168-hour control trajectory is a single action, and the advantage (episode return minus V(design)) is applied to all 168 hourly actions. The per-hour rewards are discarded, there is no GAE, and the credit assignment is very noisy.", "Whole episode as one action: ")
bullet("the critic only sees the design, so it can't explain the large return swings between scenarios. The PPO value loss stayed in the hundreds to thousands, and the returns are not normalised or scaled.", "Weak baseline and unscaled returns: ")
bullet("the policy entropy barely moved (308.9 to 307.4), so the policy hardly changed. The improvement in validation reward (about -387 to -169) tracks the design mean falling from about 50 kWp to about 10 to 20 kWp, not better control.", "Policy barely learned: ")
bullet("RL4CO is a library for combinatorial optimisation (routing, scheduling). It has no co-design support. Only its PPO loss is used here, with a hand-written stand-in environment and the design learner copied from the SB3 script, so it gets no real advantage for co-design.", "Not built for this problem: ")
p("Next step: apply the same design-distribution fixes and reward scaling as the stabilised SB3 run, then rerun before drawing conclusions.")

