body, images = [], []


def run(t, b=False, i=False, color=None, size=None):
    rpr = ("<w:b/>" if b else "") + ("<w:i/>" if i else "")
    rpr += f'<w:color w:val="{color}"/>' if color else ""
    rpr += f'<w:sz w:val="{size}"/>' if size else ""
    return f'<w:r><w:rPr>{rpr}</w:rPr><w:t xml:space="preserve">{escape(t)}</w:t></w:r>'


def para(runs, style=None, ind=None, after=120, keep=False):
    ppr = (f'<w:pStyle w:val="{style}"/>' if style else "") + ("<w:keepNext/>" if keep else "")
    ppr += f'<w:spacing w:after="{after}"/>'
    ppr += f'<w:ind w:left="{ind}" w:hanging="260"/>' if ind else ""
    body.append(f"<w:p><w:pPr>{ppr}</w:pPr>{runs}</w:p>")


def h1(t):
    para(run(t), "Heading1", keep=True)


def p(t, **k):
    para(run(t, **k))


def bullet(t, lead=None):
    para(run("•\t") + (run(lead, b=True) if lead else "") + run(t), ind=360, after=60)


def table(rows, widths):
    borders = "".join(f'<w:{s} w:val="single" w:sz="4" w:color="BFC6D0"/>' for s in ("top", "left", "bottom", "right", "insideH", "insideV"))
    x = f'<w:tbl><w:tblPr><w:tblW w:w="0" w:type="auto"/><w:tblBorders>{borders}</w:tblBorders></w:tblPr><w:tblGrid>'
    x += "".join(f'<w:gridCol w:w="{w}"/>' for w in widths) + "</w:tblGrid>"
    for ri, r in enumerate(rows):
        x += "<w:tr>"
        for w, c in zip(widths, r):
            shade = '<w:shd w:val="clear" w:color="auto" w:fill="1B3050"/>' if ri == 0 else ""
            cell = run(c, b=ri == 0, color="FFFFFF" if ri == 0 else None, size=20)
            x += f'<w:tc><w:tcPr><w:tcW w:w="{w}" w:type="dxa"/>{shade}</w:tcPr><w:p><w:pPr><w:spacing w:after="40"/></w:pPr>{cell}</w:p></w:tc>'
        x += "</w:tr>"
    body.append(x + '</w:tbl><w:p><w:pPr><w:spacing w:after="120"/></w:pPr></w:p>')


def image(name, caption, width_in=6.2):
    data = (FIGS / name).read_bytes()
    w, h = struct.unpack(">II", data[16:24])
    n = len(images) + 1
    images.append((f"image{n}.png", data))
    cx = int(width_in * 914400)
    cy = int(cx * h / w)
    A = "http://schemas.openxmlformats.org/drawingml/2006/main"
    P = "http://schemas.openxmlformats.org/drawingml/2006/picture"
    body.append(
        f'<w:p><w:pPr><w:keepNext/><w:spacing w:after="40"/></w:pPr><w:r><w:drawing>'
        f'<wp:inline distT="0" distB="0" distL="0" distR="0"><wp:extent cx="{cx}" cy="{cy}"/>'
        f'<wp:docPr id="{n}" name="{name}" descr="{escape(caption)}"/>'
        f'<a:graphic xmlns:a="{A}"><a:graphicData uri="{P}"><pic:pic xmlns:pic="{P}">'
        f'<pic:nvPicPr><pic:cNvPr id="{n}" name="{name}"/><pic:cNvPicPr/></pic:nvPicPr>'
        f'<pic:blipFill><a:blip r:embed="rId{n + 10}"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill>'
        f'<pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="{cx}" cy="{cy}"/></a:xfrm>'
        f'<a:prstGeom prst="rect"><a:avLst/></a:prstGeom></pic:spPr></pic:pic></a:graphicData></a:graphic>'
        f'</wp:inline></w:drawing></w:r></w:p>'
    )
    para(run(caption, i=True, color="6B7385", size=18), after=200)


